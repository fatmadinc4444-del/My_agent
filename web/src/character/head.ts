import * as THREE from 'three';
import { HEAD_SDF, JAW_PIVOT, MOUTH_TARGET, RAY_ORIGIN } from './headShape';
import { evalSdf, rayToSurface, sdfNormal, type V3 } from './sdf';
import { BONE_INDEX, HEAD_CENTER } from './skeletonDef';
import { smoothstep } from '../math/spring';

/**
 * Procedural head with a real mouth.
 *
 * Topology: an azimuthal polar grid centred on the mouth. Ring 0 is the back of
 * the mouth cavity, then the inner (wet) lip, the lip contact line, the
 * vermilion, the face, and finally the back of the skull (the opposite pole).
 * Every ring is an ellipse in "mouth space", so lip shapes are just
 * parameters, and every morph target is generated by re-running the generator
 * with different parameters and storing the difference (exact, no sculpting).
 */

export interface MouthParams {
  width: number;
  cornerLift: number;
  upperRaise: number;
  lowerDrop: number;
  protrude: number;
  round: number;
  rollLower: number;
  press: number;
  cheek: number;
}

const BASE: MouthParams = { width: 1, cornerLift: 0, upperRaise: 0, lowerDrop: 0, protrude: 0, round: 0, rollLower: 0, press: 0, cheek: 0 };

/** ARKit-compatible names so an artist-made GLB can replace this head 1:1. */
export const HEAD_MORPHS: Record<string, Partial<MouthParams>> = {
  mouthStretch: { width: 1.15, press: 0.3 },
  mouthSmile: { cornerLift: 0.042, width: 1.09, cheek: 1, upperRaise: 0.006 },
  mouthFrown: { cornerLift: -0.034, width: 0.97 },
  mouthFunnel: { width: 0.74, round: 0.8, protrude: 0.0075, upperRaise: 0.02, lowerDrop: 0.022 },
  mouthPucker: { width: 0.6, round: 0.6, protrude: 0.011 },
  mouthUpperUp: { upperRaise: 0.034 },
  mouthLowerDown: { lowerDrop: 0.042 },
  mouthRollLower: { rollLower: 1 },
  mouthPress: { press: 1 },
};
export const HEAD_MORPH_NAMES = Object.keys(HEAD_MORPHS);

const W0 = 0.2;
const GAP = 0.0032;
const HU = 0.05;
const HL = 0.066;
const DW = 0.022;
const SEG = 128;

// lip / cavity rings (u) and face rings (v)
const U: number[] = [-3, -2.7, -2.35, -2.0, -1.65, -1.35, -1.1, -0.85, -0.62, -0.42, -0.25, -0.11, 0, 0.07, 0.16, 0.27, 0.39, 0.52, 0.65, 0.77, 0.87, 0.95, 1];
const NV = 64;
const V: number[] = Array.from({ length: NV }, (_, k) => (k + 1) / NV);

const C0 = RAY_ORIGIN;
const m = new THREE.Vector3(MOUTH_TARGET[0] - C0[0], MOUTH_TARGET[1] - C0[1], MOUTH_TARGET[2] - C0[2]).normalize();
const tx = new THREE.Vector3(1, 0, 0);
const ty = new THREE.Vector3().crossVectors(m, tx).normalize();

const CHEEK_L = new THREE.Vector3(0.05, -0.028, 0.085);

function bell(u: number) {
  return Math.pow(Math.sin(Math.PI * Math.min(Math.max(u * 0.85 + 0.15, 0), 1)), 0.6);
}

interface P2 {
  x: number;
  y: number;
  fwd: number;
}

/** Lip ring point in mouth space (radians) + forward offset (metres). */
function lip2D(u: number, a: number, P: MouthParams, out: P2): P2 {
  const ca = Math.cos(a);
  const sa = Math.sin(a);
  const upper = sa >= 0;
  const asa = Math.abs(sa);
  const W = W0 * P.width;
  const xn = ca;
  const corner = Math.pow(Math.abs(ca), 3);
  const taper = 1 - 0.75 * Math.pow(Math.abs(ca), 6);
  const edgeH = GAP * (1 - P.press) + (upper ? P.upperRaise : P.lowerDrop);
  const bowU = 1 + 0.2 * Math.exp(-(((Math.abs(xn) - 0.3) / 0.17) ** 2)) - 0.14 * Math.exp(-((xn / 0.11) ** 2));
  const bowL = 1 + 0.1 * Math.exp(-((xn / 0.45) ** 2));
  const lipH = (upper ? HU * bowU : HL * bowL) * (1 - 0.42 * P.press);
  const T = (upper ? 0.0037 : 0.0049) * (1 - 0.5 * P.press) * taper;
  let rx: number;
  let ry: number;
  let fwd: number;
  let yOff = 0;
  if (u >= 0) {
    rx = W + DW * u * P.width;
    ry = edgeH + lipH * u;
    ry += P.round * u * Math.max(0, 0.42 * rx - ry);
    fwd = T * bell(u) + P.protrude * (1 - 0.6 * u) * taper;
  } else if (u >= -1) {
    const q = -u;
    rx = W * (1 - 0.04 * q);
    ry = edgeH + 0.028 * Math.pow(q, 1.5);
    fwd = T * bell(0) * (1 - q) - 0.0075 * Math.pow(q, 1.3) + P.protrude * (1 - 0.4 * q) * taper;
  } else {
    const q = Math.min(1, (-u - 1) / 2);
    const shrink = 1 - q * q * q;
    rx = W * (0.96 - 0.04 * q) * shrink;
    ry = (edgeH + 0.028) * shrink + 0.07 * Math.sin(Math.PI * q) * (1 - q * 0.3);
    fwd = T * 0 - 0.0075 - 0.04 * Math.pow(q, 0.85) + P.protrude * 0.6;
    yOff = -0.03 * q;
  }
  let y = ry * sa + yOff + P.cornerLift * corner * (u >= -1 ? 1 : 0.5);
  if (!upper && P.rollLower > 0) {
    const r = P.rollLower;
    y += r * 0.03 * Math.pow(asa, 0.6) * (u >= 0 ? 1 - 0.35 * u : 1);
    fwd -= r * 0.0055 * (u >= 0 ? 1 - 0.5 * u : 1) * taper;
  }
  out.x = rx * ca;
  out.y = y;
  out.fwd = fwd;
  return out;
}

const tmpN: V3 = [0, 0, 0];
const dir = new THREE.Vector3();

function project2D(x: number, y: number, outP: THREE.Vector3, outN: THREE.Vector3) {
  const th = Math.hypot(x, y);
  const ps = Math.atan2(y, x);
  const st = Math.sin(th);
  dir.copy(m).multiplyScalar(Math.cos(th));
  dir.addScaledVector(tx, st * Math.cos(ps)).addScaledVector(ty, st * Math.sin(ps)).normalize();
  const t = rayToSurface(HEAD_SDF, C0, dir.x, dir.y, dir.z);
  outP.set(C0[0] + dir.x * t, C0[1] + dir.y * t, C0[2] + dir.z * t);
  sdfNormal(HEAD_SDF, outP.x, outP.y, outP.z, tmpN);
  outN.set(tmpN[0], tmpN[1], tmpN[2]);
}

interface VertInfo {
  kind: 0 | 1; // 0 = lip/cavity ring, 1 = face ring
  u: number;
  v: number;
  a: number;
}

function generate(P: MouthParams, info: VertInfo[] | null, base?: Float32Array): Float32Array {
  const rings = U.length + V.length;
  const pos = new Float32Array(rings * SEG * 3);
  const p2 = { x: 0, y: 0, fwd: 0 };
  const b0 = { x: 0, y: 0, fwd: 0 };
  const P3 = new THREE.Vector3();
  const N3 = new THREE.Vector3();
  let vi = 0;
  for (let r = 0; r < rings; r++) {
    const isLip = r < U.length;
    for (let k = 0; k < SEG; k++) {
      const a = (k / SEG) * Math.PI * 2;
      let fwd: number;
      let v = 0;
      if (isLip) {
        lip2D(U[r], a, P, p2);
        fwd = p2.fwd;
      } else {
        v = V[r - U.length];
        if (base && v > 0.32) {
          // morphs never reach this far from the mouth: reuse the base surface
          pos[vi * 3] = base[vi * 3];
          pos[vi * 3 + 1] = base[vi * 3 + 1];
          pos[vi * 3 + 2] = base[vi * 3 + 2];
          vi++;
          continue;
        }
        const pv = Math.pow(v, 1.35);
        lip2D(1, a, BASE, b0);
        lip2D(1, a, P, p2);
        const fall = 1 - smoothstep(0, 0.2, v);
        const cx = Math.PI * Math.cos(a);
        const cy = Math.PI * Math.sin(a);
        const bx = b0.x + (cx - b0.x) * pv;
        const by = b0.y + (cy - b0.y) * pv;
        const dx = (p2.x - b0.x) * fall;
        const dy = (p2.y - b0.y) * fall;
        p2.x = bx + dx;
        p2.y = by + dy;
        const corner = Math.pow(Math.abs(Math.cos(a)), 10);
        fwd = P.protrude * 0.45 * (1 - smoothstep(0, 0.16, v)) - 0.0016 * corner * Math.exp(-((v / 0.035) ** 2)) * (1 + P.cheek);
      }
      project2D(p2.x, p2.y, P3, N3);
      P3.addScaledVector(N3, fwd);
      if (!isLip && P.cheek > 0) {
        for (const sx of [1, -1]) {
          const ddx = P3.x - CHEEK_L.x * sx;
          const ddy = P3.y - CHEEK_L.y;
          const ddz = P3.z - CHEEK_L.z;
          const g = Math.exp(-(ddx * ddx + ddy * ddy * 1.4 + ddz * ddz) / (0.024 * 0.024));
          P3.addScaledVector(N3, P.cheek * 0.0042 * g);
          P3.y += P.cheek * 0.004 * g;
        }
      }
      pos[vi * 3] = P3.x;
      pos[vi * 3 + 1] = P3.y;
      pos[vi * 3 + 2] = P3.z;
      if (info) info.push({ kind: isLip ? 0 : 1, u: isLip ? U[r] : 1, v, a });
      vi++;
    }
  }
  return pos;
}

/**
 * Tangential relaxation on the SDF surface: Laplacian smoothing followed by
 * Newton projection back to the zero set. Evens out vertex spacing where the
 * radial projection is grazing (eye sockets, under the nose) -> no jaggies.
 */
function relax(pos: Float32Array, iters: number) {
  const rings = U.length + V.length;
  const r0 = U.length + Math.round(0.1 * NV);
  const r1 = rings - 2;
  const tmp = new Float32Array(pos.length);
  const n: V3 = [0, 0, 0];
  for (let it = 0; it < iters; it++) {
    tmp.set(pos);
    for (let r = r0; r <= r1; r++) {
      for (let k = 0; k < SEG; k++) {
        const i = r * SEG + k;
        const a = (r - 1) * SEG + k;
        const b = (r + 1) * SEG + k;
        const c = r * SEG + ((k + 1) % SEG);
        const d = r * SEG + ((k + SEG - 1) % SEG);
        for (let j = 0; j < 3; j++) {
          const avg = (tmp[a * 3 + j] + tmp[b * 3 + j] + tmp[c * 3 + j] + tmp[d * 3 + j]) * 0.25;
          pos[i * 3 + j] = tmp[i * 3 + j] * 0.4 + avg * 0.6;
        }
        let x = pos[i * 3];
        let y = pos[i * 3 + 1];
        let z = pos[i * 3 + 2];
        for (let q = 0; q < 3; q++) {
          const dist = evalSdf(HEAD_SDF, x, y, z);
          sdfNormal(HEAD_SDF, x, y, z, n);
          x -= n[0] * dist;
          y -= n[1] * dist;
          z -= n[2] * dist;
        }
        pos[i * 3] = x;
        pos[i * 3 + 1] = y;
        pos[i * 3 + 2] = z;
      }
    }
  }
}

function buildIndex(): number[] {
  const rings = U.length + V.length;
  const idx: number[] = [];
  for (let r = 0; r < rings - 1; r++) {
    const r0 = r * SEG;
    const r1 = (r + 1) * SEG;
    for (let k = 0; k < SEG; k++) {
      const k1 = (k + 1) % SEG;
      // winding: rings grow outward from the mouth; outward normals face away from head centre
      idx.push(r0 + k, r1 + k, r1 + k1, r0 + k, r1 + k1, r0 + k1);
    }
  }
  return idx;
}

export interface HeadBuild {
  geometry: THREE.BufferGeometry;
  mouthCenter: THREE.Vector3; // head-local
  mouthAxis: THREE.Vector3;
}

function normalsFor(pos: Float32Array, index: THREE.BufferAttribute): Float32Array {
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  g.setIndex(index);
  g.computeVertexNormals();
  return g.getAttribute('normal').array as Float32Array;
}

export function buildHead(): HeadBuild {
  const info: VertInfo[] = [];
  const raw = generate(BASE, info);
  const nv = info.length;
  const base = raw.slice();
  relax(base, 12);
  const index = new THREE.Uint16BufferAttribute(buildIndex(), 1);
  const baseN = normalsFor(base, index);

  // the mouth cavity rings: replace normals with ones that face inward-forward
  // (prevents the cavity catching lamp light like an outer surface)

  const geo = new THREE.BufferGeometry();
  const bind = new Float32Array(nv * 3);
  for (let i = 0; i < nv; i++) {
    bind[i * 3] = base[i * 3] + HEAD_CENTER[0];
    bind[i * 3 + 1] = base[i * 3 + 1] + HEAD_CENTER[1];
    bind[i * 3 + 2] = base[i * 3 + 2] + HEAD_CENTER[2];
  }
  geo.setAttribute('position', new THREE.BufferAttribute(bind, 3));
  geo.setAttribute('normal', new THREE.BufferAttribute(baseN, 3));
  geo.setIndex(index);

  // ---- per-vertex masks: x = lip, y = cavity, z = blush
  const mask = new Float32Array(nv * 4);
  const skinIndex = new Uint16Array(nv * 4);
  const skinWeight = new Float32Array(nv * 4);
  const hb = BONE_INDEX['head'];
  const jb = BONE_INDEX['jaw'];
  // mouth line height (head-local) for face weights
  const mouthP = new THREE.Vector3();
  const mouthN = new THREE.Vector3();
  project2D(0, 0, mouthP, mouthN);
  for (let i = 0; i < nv; i++) {
    const it = info[i];
    const x = base[i * 3];
    const y = base[i * 3 + 1];
    const z = base[i * 3 + 2];
    let lip = 0;
    let cav = 0;
    let jaw = 0;
    const sa = Math.sin(it.a);
    if (it.kind === 0) {
      lip = 1 - smoothstep(0.86, 1.0, it.u);
      cav = smoothstep(-0.25, -1.3, it.u);
      const depthFade = smoothstep(-1.2, -3, it.u);
      jaw = (0.5 - 0.5 * Math.max(-1, Math.min(1, sa * 4))) * (1 - depthFade) + 0.5 * depthFade;
    } else {
      // region below the mouth line rotates with the jaw
      const line = mouthP.y + 0.006 + 0.55 * x * x;
      const below = smoothstep(0.004, -0.024, y - line);
      const front = smoothstep(-0.055, 0.03, z);
      const nearCorner = Math.exp(-((it.v / 0.03) ** 2)) * Math.pow(Math.abs(Math.cos(it.a)), 2);
      jaw = below * front;
      // keep continuity with the lip ring weights near the lips
      const nearLip = Math.exp(-((it.v / 0.06) ** 2));
      const lipW = 0.5 - 0.5 * Math.max(-1, Math.min(1, sa * 4));
      jaw = jaw * (1 - nearLip) + lipW * nearLip;
      jaw = jaw * (1 - nearCorner) + 0.5 * nearCorner;
    }
    let blush = 0;
    for (const sx of [1, -1]) {
      const dx = x - 0.056 * sx;
      const dy = y + 0.022;
      const dz = z - 0.078;
      blush += Math.exp(-(dx * dx * 0.8 + dy * dy * 1.6 + dz * dz) / (0.026 * 0.026));
    }
    mask[i * 4] = lip;
    mask[i * 4 + 1] = cav;
    mask[i * 4 + 2] = Math.min(1, blush);
    {
      // precomputed ambient occlusion from the sculpt SDF
      const nx = baseN[i * 3];
      const ny = baseN[i * 3 + 1];
      const nz = baseN[i * 3 + 2];
      let occ = 0;
      let sc = 1;
      for (let k = 1; k <= 5; k++) {
        const h = 0.004 * k;
        const d = evalSdf(HEAD_SDF, x + nx * h, y + ny * h, z + nz * h);
        occ += (h - d) * sc;
        sc *= 0.75;
      }
      let ao = Math.max(0, Math.min(1, 1 - 16 * occ));
      // the eye sockets also get darker toward the eyeball (lids & lashes)
      for (const ex of [0.043, -0.043]) {
        const dd = Math.hypot(x - ex, y - 0.012, z - 0.0985);
        ao *= 1 - 0.12 * Math.exp(-(((dd - 0.03) / 0.005) ** 2));
      }
      mask[i * 4 + 3] = it.kind === 0 && it.u < 0 ? 0.3 : ao;
    }
    skinIndex[i * 4] = hb;
    skinIndex[i * 4 + 1] = jb;
    skinWeight[i * 4] = 1 - jaw;
    skinWeight[i * 4 + 1] = jaw;
  }
  geo.setAttribute('aFace', new THREE.BufferAttribute(mask, 4));
  geo.setAttribute('skinIndex', new THREE.BufferAttribute(skinIndex, 4));
  geo.setAttribute('skinWeight', new THREE.BufferAttribute(skinWeight, 4));

  // ---- morph targets (relative)
  const mp: THREE.BufferAttribute[] = [];
  const mn: THREE.BufferAttribute[] = [];
  for (const name of HEAD_MORPH_NAMES) {
    const P = { ...BASE, ...HEAD_MORPHS[name] };
    const tgt = generate(P, null, raw);
    // deltas are taken between unrelaxed surfaces and applied to the relaxed base
    const dp = new Float32Array(nv * 3);
    for (let i = 0; i < nv * 3; i++) dp[i] = tgt[i] - raw[i];
    const moved = base.slice();
    for (let i = 0; i < nv * 3; i++) moved[i] += dp[i];
    const tn = normalsFor(moved, index);
    const dn = new Float32Array(nv * 3);
    for (let i = 0; i < nv * 3; i++) dn[i] = tn[i] - baseN[i];
    const a = new THREE.BufferAttribute(dp, 3);
    a.name = name;
    mp.push(a);
    const b = new THREE.BufferAttribute(dn, 3);
    b.name = name;
    mn.push(b);
  }
  geo.morphAttributes.position = mp;
  geo.morphAttributes.normal = mn;
  geo.morphTargetsRelative = true;
  geo.computeBoundingSphere();
  if (geo.boundingSphere) geo.boundingSphere.radius += 0.05;

  return { geometry: geo, mouthCenter: mouthP.clone(), mouthAxis: m.clone() };
}

/** Head-local point on the skin along a direction from the ray origin. */
export function headSurface(dirx: number, diry: number, dirz: number, out = new THREE.Vector3(), outN?: THREE.Vector3) {
  const l = Math.hypot(dirx, diry, dirz);
  const t = rayToSurface(HEAD_SDF, C0, dirx / l, diry / l, dirz / l);
  out.set(C0[0] + (dirx / l) * t, C0[1] + (diry / l) * t, C0[2] + (dirz / l) * t);
  if (outN) {
    sdfNormal(HEAD_SDF, out.x, out.y, out.z, tmpN);
    outN.set(tmpN[0], tmpN[1], tmpN[2]);
  }
  return out;
}

